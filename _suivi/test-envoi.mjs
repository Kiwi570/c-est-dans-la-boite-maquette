import { chromium } from 'playwright';
import sharp from 'sharp';
import { demarrerServeur } from '../_audit/serveur.mjs';
const srv = await demarrerServeur(process.cwd());
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('pageerror', (e) => console.log('ERR', String(e)));
await p.goto(srv.adresse + '/sur-mesure#composer'); await p.waitForTimeout(3600);
await p.click('input[value=vacances]'); await p.waitForTimeout(200);
const s1 = await p.screenshot();
await p.evaluate(() => document.querySelector('[data-email]').scrollIntoView({ block: 'center' })); await p.waitForTimeout(600);
await p.evaluate(() => { document.querySelector('[data-email]').addEventListener('click', (e) => e.preventDefault()); });
await p.click('[data-email]'); await p.waitForTimeout(500);
const s2 = await p.screenshot(); await p.waitForTimeout(1500);
const s3 = await p.screenshot();
await p.goto(srv.adresse + '/contact'); await p.waitForTimeout(3600);
await p.click('[data-copier]'); await p.waitForTimeout(300);
const s4 = await p.screenshot();
const t = await Promise.all([s1, s2, s3, s4].map((x) => sharp(x).resize(720).toBuffer()));
await sharp({ create: { width: 1440, height: 900, channels: 3, background: '#888' } }).composite(t.map((x, i) => ({ input: x, left: (i % 2) * 720, top: Math.floor(i / 2) * 450 }))).jpeg().toFile('/home/claude/envoi.jpg');
await b.close(); await srv.fermer(); process.exit(0);
