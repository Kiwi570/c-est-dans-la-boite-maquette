import { chromium } from 'playwright';
import sharp from 'sharp';
import { demarrerServeur } from '../_audit/serveur.mjs';
const srv = await demarrerServeur(process.cwd());
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('pageerror', (e) => console.log('ERR', String(e)));
await p.goto(srv.adresse + '/'); await p.waitForTimeout(3600);
const s1 = await p.screenshot();
await p.click('[data-melanger]'); await p.waitForTimeout(1500);
const s2 = await p.screenshot();
console.log(await p.textContent('[data-pile-legende]'));
await p.evaluate(() => document.querySelector('#format').scrollIntoView()); await p.waitForTimeout(1500);
const s3 = await p.screenshot();
const box = await p.locator('.b3-scene').boundingBox();
await p.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await p.mouse.down(); await p.mouse.move(box.x + box.width / 2 + 160, box.y + box.height / 2, { steps: 8 });
await p.waitForTimeout(300); const s4 = await p.screenshot(); await p.mouse.up();
const t = await Promise.all([s1, s2, s3, s4].map((x) => sharp(x).resize(720).toBuffer()));
await sharp({ create: { width: 1440, height: 900, channels: 3, background: '#888' } }).composite(t.map((x, i) => ({ input: x, left: (i % 2) * 720, top: Math.floor(i / 2) * 450 }))).jpeg().toFile('/home/claude/pile.jpg');
await b.close(); await srv.fermer(); process.exit(0);
